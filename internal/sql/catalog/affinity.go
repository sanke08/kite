package catalog

import "strings"

// Affinity is the type a column PREFERS. It is not a constraint.
//
// WHY a preference and not a type: a column declared INTEGER can hold text.
// SQL as implemented here is dynamically typed — the value carries its own
// type, and the column's declared type only decides what a value is nudged
// toward on the way in. Text that cannot convert is stored as text.
//
// EG: CREATE TABLE t(a INTEGER)
//
//	INSERT INTO t VALUES ('42')     stored as Integer(42)   — converted
//	INSERT INTO t VALUES ('hello')  stored as Text("hello") — kept as-is
//
// WITHOUT: declaring a type would have to reject the second insert, which
// would fail thousands of corpus records that expect it to succeed.
type Affinity int

const (
	// Blob is the "no affinity" case: values are stored exactly as given,
	// with no conversion attempted at all.
	Blob Affinity = iota
	Text
	Numeric
	Integer
	Real
)

// affinityNames is indexed by Affinity, for .schema output and errors.
var affinityNames = [...]string{
	Blob:    "BLOB",
	Text:    "TEXT",
	Numeric: "NUMERIC",
	Integer: "INTEGER",
	Real:    "REAL",
}

func (affinity Affinity) String() string {
	if int(affinity) < len(affinityNames) {
		return affinityNames[affinity]
	}
	return "BLOB"
}

// AffinityOf maps a declared type name to its affinity, using SQLite's rules.
//
// WHY substring matching rather than an exact table of type names: SQL lets
// you declare a column as anything at all — VARCHAR(255), BIGINT, DOUBLE
// PRECISION, or a word no standard mentions. The rules below classify any of
// them without needing a list that would always be incomplete.
//
// The order matters. Each rule is checked only if every rule above it missed:
//
//  1. contains INT     -> Integer    INTEGER, BIGINT, INT8, POINT (yes, really)
//  2. contains CHAR,
//     CLOB or TEXT     -> Text       VARCHAR(255), NCHAR, TEXT
//  3. contains BLOB,
//     or is empty      -> Blob       BLOB, or no declared type at all
//  4. contains REAL,
//     FLOA or DOUB     -> Real       REAL, FLOAT, DOUBLE PRECISION
//  5. anything else    -> Numeric    DECIMAL(10,5), BOOLEAN, DATE, VARIANT
//
// TRAP: rule 1 catching POINT is not a bug to fix. SQLite behaves exactly this
// way, and the corpus's expected values were generated by SQLite — so a
// "smarter" classification would fail records the engine got right.
func AffinityOf(declaredType string) Affinity {
	upper := strings.ToUpper(declaredType)

	switch {
	case strings.Contains(upper, "INT"):
		return Integer
	case strings.Contains(upper, "CHAR"),
		strings.Contains(upper, "CLOB"),
		strings.Contains(upper, "TEXT"):
		return Text
	case strings.Contains(upper, "BLOB"), upper == "":
		return Blob
	case strings.Contains(upper, "REAL"),
		strings.Contains(upper, "FLOA"),
		strings.Contains(upper, "DOUB"):
		return Real
	}
	return Numeric
}
